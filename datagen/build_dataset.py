"""
Validate the labelled items and build the train / val / test datasets.

    python datagen/build_dataset.py

Inputs:
    datagen/raw/<topic>.json        retrieved top-20 passages per topic
    datagen/splits.json             topic -> test / val / train
    datagen/labels/batch_NN.jsonl   labels written by the labellers (SPEC.md)

Outputs:
    data/train.jsonl, data/val.jsonl     chat-format training examples (prompt v1)
    eval/data/test_v2.jsonl              held-out test set (new items + 27 baseline items)
    datagen/rejected.jsonl               every rejected item with its reasons
    datagen/dataset_report.md            counts and rejection summary

Extra items are generated by script, with no labeller needed: an
off-topic unanswerable item pairs a topic's question with passages
from a different domain, and the answer is always the refusal.
"""

import json
import random
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from prompts import REFUSAL, build_messages  # noqa: E402
from eval.metrics import (  # noqa: E402
    CITATION, citations_in, question_overlap, score_answer, split_sentences,
)

RAW_DIR = ROOT / "datagen" / "raw"
LABEL_DIR = ROOT / "datagen" / "labels"
SPLITS = ROOT / "datagen" / "splits.json"
DATA_DIR = ROOT / "data"
TEST_OUT = ROOT / "eval" / "data" / "test_v2.jsonl"
BASELINE_TEST = ROOT / "eval" / "data" / "baseline_test.jsonl"
REJECTED = ROOT / "datagen" / "rejected.jsonl"
REPORT = ROOT / "datagen" / "dataset_report.md"

ITEMS = {"seed", "gen", "hard_neg", "partial"}
LABELS = {"answerable", "partial", "unanswerable"}
MAX_WORDS = 90
MAX_SENTENCES = 5
MIN_GROUNDEDNESS = 0.4
GAP_SENTENCE = re.compile(r"^the sources do not (say|cover|mention|state|explain|give)",
                          re.IGNORECASE)
OFFTOPIC_SHARE = 0.10


def normalise(question):
    return re.sub(r"[^a-z0-9 ]", "", question.lower()).strip()


def validate(item, passages):
    """
    Return a list of reasons the item is invalid (empty = valid).
    """

    reasons = []
    answer = item.get("answer", "").strip()
    label = item.get("label")

    if item.get("item") not in ITEMS:
        reasons.append(f"unknown item type {item.get('item')!r}")
    if label not in LABELS:
        reasons.append(f"unknown label {label!r}")
    if not item.get("question", "").strip():
        reasons.append("empty question")
    if not answer:
        return reasons + ["empty answer"]

    if item.get("item") == "hard_neg" and label != "unanswerable":
        reasons.append("hard_neg must be unanswerable")
    if item.get("item") == "gen" and label != "answerable":
        reasons.append("gen must be answerable")
    if item.get("item") == "partial" and label != "partial":
        reasons.append("partial item must be labelled partial")

    if label == "unanswerable":
        if answer != REFUSAL:
            reasons.append("unanswerable answer is not the exact refusal")
        return reasons

    if answer == REFUSAL:
        return reasons + [f"{label} item answered with the refusal"]

    sentences = split_sentences(answer)
    cited = citations_in(answer)

    if not cited:
        reasons.append("no citations")
    if any(n < 1 or n > len(passages) for n in cited):
        reasons.append(f"citation out of range {sorted(set(cited))}")
    if len(answer.split()) > MAX_WORDS:
        reasons.append(f"too long ({len(answer.split())} words)")
    if len(sentences) > MAX_SENTENCES:
        reasons.append(f"too many sentences ({len(sentences)})")

    body = sentences
    if label == "partial":
        if not sentences or not GAP_SENTENCE.match(sentences[-1]):
            reasons.append("partial answer must end with 'The sources do not say ...'")
        elif citations_in(sentences[-1]):
            reasons.append("partial gap sentence should not be cited")
        body = sentences[:-1]
        if not body:
            reasons.append("partial answer has no answered part")

    uncited = [s for s in body if not citations_in(s)]
    if uncited:
        reasons.append(f"{len(uncited)} uncited sentence(s)")

    scores = score_answer(" ".join(body), passages, True, question=item["question"])
    if scores["groundedness"] is not None and scores["groundedness"] < MIN_GROUNDEDNESS:
        reasons.append(f"low groundedness {scores['groundedness']:.0%}")
    overlap = question_overlap(answer, item["question"])
    if overlap == 0:
        reasons.append("answer shares no key words with the question")

    return reasons


def main():
    raw = {p.stem: json.loads(p.read_text(encoding="utf-8"))
           for p in RAW_DIR.glob("s*.json")}
    splits = json.loads(SPLITS.read_text())

    reserved = {normalise(json.loads(line)["question"])
                for line in open(BASELINE_TEST, encoding="utf-8")}

    accepted = defaultdict(list)
    rejected = []
    seen = set(reserved)
    label_files = sorted(LABEL_DIR.glob("batch_*.jsonl"))

    for label_file in label_files:
        for number, line in enumerate(open(label_file, encoding="utf-8"), start=1):
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError as error:
                rejected.append({"file": label_file.name, "line": number,
                                 "reasons": [f"invalid JSON: {error}"]})
                continue

            topic = raw.get(item.get("topic_id"))
            if topic is None:
                rejected.append({**item, "reasons": ["unknown topic_id"]})
                continue

            passages = topic["passages"][:5]
            reasons = validate(item, passages)

            key = normalise(item.get("question", ""))
            if key in seen:
                reasons.append("duplicate question (or reserved test question)")

            if reasons:
                rejected.append({**item, "reasons": reasons})
                continue

            seen.add(key)
            accepted[splits[topic["id"]]].append({
                "id": f"{topic['id']}-{item['item']}",
                "topic_id": topic["id"],
                "domain": topic["domain"],
                "type": item["item"],
                "label": item["label"],
                "question": item["question"].strip(),
                "answer": item["answer"].strip(),
                "passages": passages,
                "passages_top20": topic["passages"][:20],
                "answer_in_6_20": item.get("answer_in_6_20"),
                "ranks_6_20": item.get("ranks_6_20") or [],
            })

    # Scripted off-topic unanswerable items, within each split.
    rng = random.Random(7)
    for split, items in accepted.items():
        topics = sorted({i["topic_id"] for i in items})
        n_offtopic = max(1, round(len(items) * OFFTOPIC_SHARE))
        for _ in range(n_offtopic):
            asker = raw[rng.choice(topics)]
            split_topics = [t for t, sp in splits.items() if sp == split and t in raw]
            donors = [t for t in split_topics if raw[t]["domain"] != asker["domain"]]
            if not donors:
                continue
            donor = raw[rng.choice(donors)]
            item_id = f"{asker['id']}-offtopic-{donor['id']}"
            if any(i["id"] == item_id for i in items):
                continue
            items.append({
                "id": item_id, "topic_id": asker["id"], "domain": asker["domain"],
                "type": "offtopic_neg", "label": "unanswerable",
                "question": asker["question"], "answer": REFUSAL,
                "passages": donor["passages"][:5],
                "passages_top20": donor["passages"][:20],
                "answer_in_6_20": False, "ranks_6_20": [],
            })

    DATA_DIR.mkdir(exist_ok=True)

    for split in ("train", "val"):
        items = sorted(accepted.get(split, []), key=lambda i: i["id"])
        rng.shuffle(items)
        with open(DATA_DIR / f"{split}.jsonl", "w", encoding="utf-8") as file:
            for item in items:
                messages = build_messages(item["question"], item["passages"])
                messages.append({"role": "assistant", "content": item["answer"]})
                record = {k: v for k, v in item.items() if k != "passages_top20"}
                file.write(json.dumps({**record, "messages": messages},
                                      ensure_ascii=False) + "\n")

    test_items = sorted(accepted.get("test", []), key=lambda i: i["id"])
    if TEST_OUT.exists() and "--rebuild-test" not in sys.argv:
        print(f"{TEST_OUT.relative_to(ROOT)} is frozen; not rewritten "
              "(pass --rebuild-test to rebuild it).")
        test_items_written = False
    else:
        test_items_written = True
    with open(TEST_OUT if test_items_written else "/dev/null", "w",
              encoding="utf-8") as file:
        for item in test_items:
            file.write(json.dumps({
                "id": item["id"], "topic_id": item["topic_id"],
                "domain": item["domain"], "type": item["type"],
                "label": item["label"], "question": item["question"],
                "answerable": item["label"] != "unanswerable",
                "reference_answer": item["answer"],
                "passages": item["passages"],
                "passages_top20": item["passages_top20"],
                "answer_in_6_20": item["answer_in_6_20"],
                "ranks_6_20": item["ranks_6_20"],
            }, ensure_ascii=False) + "\n")
        for line in open(BASELINE_TEST, encoding="utf-8"):
            old = json.loads(line)
            file.write(json.dumps({
                **old, "topic_id": old["id"], "domain": "baseline",
                "type": "baseline",
                "label": "answerable" if old["answerable"] else "unanswerable",
                "reference_answer": None, "passages_top20": None,
                "answer_in_6_20": None, "ranks_6_20": [],
            }, ensure_ascii=False) + "\n")

    with open(REJECTED, "w", encoding="utf-8") as file:
        for item in rejected:
            file.write(json.dumps(item, ensure_ascii=False) + "\n")

    # Report
    lines = ["# Dataset report", "",
             f"Label files: {len(label_files)}. Topics retrieved: {len(raw)}.", "",
             "| Split | Items | answerable | partial | unanswerable | "
             "seed | gen | hard_neg | partial (type) | offtopic_neg |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for split in ("train", "val", "test"):
        items = accepted.get(split, [])
        labels = Counter(i["label"] for i in items)
        types = Counter(i["type"] for i in items)
        lines.append(
            f"| {split} | {len(items)} | {labels['answerable']} | {labels['partial']} | "
            f"{labels['unanswerable']} | {types['seed']} | {types['gen']} | "
            f"{types['hard_neg']} | {types['partial']} | {types['offtopic_neg']} |"
        )
    baseline_count = sum(1 for _ in open(BASELINE_TEST, encoding="utf-8"))
    lines += ["", f"`test_v2.jsonl` = {len(test_items)} new test items + "
              f"{baseline_count} baseline items = {len(test_items) + baseline_count}.",
              "", f"Rejected: {len(rejected)}", "", "| Reason | Count |", "|---|---|"]
    reasons = Counter(r.split(" (")[0].split(" [")[0]
                      for item in rejected for r in item["reasons"])
    lines += [f"| {reason} | {count} |" for reason, count in reasons.most_common()]

    words = [len(i["answer"].split()) for s in ("train", "val")
             for i in accepted.get(s, []) if i["label"] != "unanswerable"]
    if words:
        lines += ["", f"Answer length (train+val, non-refusal): mean "
                  f"{sum(words) / len(words):.0f} words, max {max(words)}."]
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
